            ?: "// TODO: no episode list was captured — verify this selector on a series page"
        val urlNote = a.detailUrl?.let { "// Detail page analysed: ${it.take(140)}" } ?: "// TODO: no detail page was captured; selectors are generic"

        return """
$urlNote
