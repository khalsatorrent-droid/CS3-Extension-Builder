    private fun loadBody(a: SiteAnalysis, cardSel: String): String {
        val d = a.detail
        val title = buildList {
            d?.title?.let { add("doc.selectFirst(${lit(it)})?.text().clean()") }
            add("doc.selectFirst(\"meta[property=og:title]\")?.attr(\"content\").clean()")
